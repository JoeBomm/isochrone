import { act, fireEvent, render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { describe, expect, it, vi } from "vitest";
import { BottomSheet, nextSnap } from "./BottomSheet";

function renderSheet(props: Partial<Parameters<typeof BottomSheet>[0]> = {}) {
  return render(
    <>
      <h1 id="title">Halfway</h1>
      <BottomSheet labelledBy="title" {...props}>
        <p>Panel content</p>
      </BottomSheet>
    </>,
  );
}

const region = () => screen.getByRole("region", { name: "Halfway" });
const handle = () => screen.getAllByRole("button")[0];

describe("nextSnap", () => {
  it("cycles peek -> half -> full -> peek", () => {
    expect(nextSnap("peek")).toBe("half");
    expect(nextSnap("half")).toBe("full");
    expect(nextSnap("full")).toBe("peek");
  });
});

describe("BottomSheet", () => {
  it("is a labelled region whose handle is a real button controlling the body", () => {
    renderSheet();
    expect(region().getAttribute("data-snap")).toBe("half");
    const button = handle();
    expect(button.tagName).toBe("BUTTON");
    expect(button.getAttribute("type")).toBe("button");
    const body = document.getElementById(button.getAttribute("aria-controls") ?? "");
    expect(body?.textContent).toBe("Panel content");
  });

  it("cycles snap points with Enter and Space", async () => {
    const user = userEvent.setup();
    renderSheet({ defaultSnap: "peek" });
    handle().focus();

    expect(handle().getAttribute("aria-label")).toBe("Expand panel");
    await user.keyboard("{Enter}");
    expect(region().getAttribute("data-snap")).toBe("half");
    expect(handle().getAttribute("aria-label")).toBe("Expand panel to full screen");

    await user.keyboard(" ");
    expect(region().getAttribute("data-snap")).toBe("full");
    expect(handle().getAttribute("aria-label")).toBe("Collapse panel");

    await user.keyboard("{Enter}");
    expect(region().getAttribute("data-snap")).toBe("peek");
    expect(document.activeElement).toBe(handle());
  });

  it("steps with ArrowUp/ArrowDown without wrapping", async () => {
    const user = userEvent.setup();
    renderSheet({ defaultSnap: "half" });
    handle().focus();
    await user.keyboard("{ArrowUp}");
    expect(region().getAttribute("data-snap")).toBe("full");
    await user.keyboard("{ArrowUp}");
    expect(region().getAttribute("data-snap")).toBe("full");
    await user.keyboard("{ArrowDown}{ArrowDown}{ArrowDown}");
    expect(region().getAttribute("data-snap")).toBe("peek");
  });

  it("exposes aria-expanded on the handle (collapsed only at peek)", async () => {
    const user = userEvent.setup();
    renderSheet({ defaultSnap: "peek" });
    expect(handle().getAttribute("aria-expanded")).toBe("false");
    await user.click(handle());
    expect(handle().getAttribute("aria-expanded")).toBe("true");
    await user.click(handle());
    expect(handle().getAttribute("aria-expanded")).toBe("true");
    await user.click(handle());
    expect(handle().getAttribute("aria-expanded")).toBe("false");
  });

  it("steps on a swipe and captures the pointer", () => {
    const capture = vi.fn();
    renderSheet({ defaultSnap: "half" });
    const button = handle();
    (button as HTMLButtonElement & { setPointerCapture: (id: number) => void }).setPointerCapture = capture;
    fireEvent.pointerDown(button, { pointerId: 7, clientY: 400 });
    expect(capture).toHaveBeenCalledWith(7);
    fireEvent.pointerUp(button, { pointerId: 7, clientY: 300 });
    expect(region().getAttribute("data-snap")).toBe("full");
  });

  it("suppresses only the click that ends a swipe", () => {
    renderSheet({ defaultSnap: "half" });
    const button = handle();
    fireEvent.pointerDown(button, { pointerId: 1, clientY: 300 });
    fireEvent.pointerUp(button, { pointerId: 1, clientY: 400 });
    expect(region().getAttribute("data-snap")).toBe("peek");
    fireEvent.click(button, { detail: 1 }); // the click generated by the swipe
    expect(region().getAttribute("data-snap")).toBe("peek");
  });

  it("does not swallow a later keyboard activation when no click followed the swipe", async () => {
    const user = userEvent.setup();
    renderSheet({ defaultSnap: "half" });
    const button = handle();
    // Swipe ends off the handle, so the browser fires no click afterwards.
    fireEvent.pointerDown(button, { pointerId: 1, clientY: 300 });
    fireEvent.pointerUp(button, { pointerId: 1, clientY: 400 });
    expect(region().getAttribute("data-snap")).toBe("peek");
    button.focus();
    await user.keyboard("{Enter}");
    expect(region().getAttribute("data-snap")).toBe("half");
  });

  it("forgets the swipe after a short timeout even without a keydown", () => {
    vi.useFakeTimers();
    try {
      renderSheet({ defaultSnap: "half" });
      const button = handle();
      fireEvent.pointerDown(button, { pointerId: 1, clientY: 300 });
      fireEvent.pointerUp(button, { pointerId: 1, clientY: 400 });
      act(() => {
        vi.advanceTimersByTime(1000);
      });
      fireEvent.click(button, { detail: 1 });
      expect(region().getAttribute("data-snap")).toBe("half");
    } finally {
      vi.useRealTimers();
    }
  });

  it("supports a controlled snap", async () => {
    const user = userEvent.setup();
    const onSnapChange = vi.fn();
    const { rerender } = renderSheet({ snap: "full", onSnapChange });
    await user.click(handle());
    expect(onSnapChange).toHaveBeenCalledWith("peek");
    // still "full" until the parent updates the prop
    expect(region().getAttribute("data-snap")).toBe("full");
    rerender(
      <>
        <h1 id="title">Halfway</h1>
        <BottomSheet labelledBy="title" snap="peek" onSnapChange={onSnapChange}>
          <p>Panel content</p>
        </BottomSheet>
      </>,
    );
    expect(region().getAttribute("data-snap")).toBe("peek");
  });

  it("renders an optional peek summary outside the body and flags it for CSS", () => {
    const { container, rerender } = renderSheet({ snap: "peek", summary: <button type="button">Find meeting points</button> });
    const section = container.querySelector(".sheet")!;
    expect(section.hasAttribute("data-summary")).toBe(true);
    const summary = container.querySelector(".sheet__summary")!;
    expect(summary.textContent).toBe("Find meeting points");
    // the summary is not inside the collapsible body the handle controls
    const body = document.getElementById(handle().getAttribute("aria-controls")!)!;
    expect(body.contains(summary)).toBe(false);
    expect(handle().nextElementSibling).toBe(summary);

    rerender(
      <>
        <h1 id="title">Halfway</h1>
        <BottomSheet labelledBy="title">
          <p>Panel content</p>
        </BottomSheet>
      </>,
    );
    expect(container.querySelector(".sheet")!.hasAttribute("data-summary")).toBe(false);
    expect(container.querySelector(".sheet__summary")).toBeNull();
  });
});
